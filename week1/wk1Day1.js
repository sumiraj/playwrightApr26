// Week 1 - Day 1 Assignment
// Declare variables using var for different data types and verify using typeof
// Theme: Teenage Mutant Ninja Turtles

// a) firstName - String (one of the four turtles)
var firstName = "Leonardo";
console.log("firstName : " + firstName + " :: typeof :: " + typeof(firstName));

// b) companyName - String (April O'Neil's news agency from TMNT)
var companyName = "Channel 6 News";
console.log("companyName : " + companyName + " :: typeof :: " + typeof(companyName));

// c) mobileNumber - Number (referencing TMNT - 1987 was the year the original animated series aired)
var mobileNumber = 9871984123;
console.log("mobileNumber : " + mobileNumber + " :: typeof :: " + typeof(mobileNumber));

// d) isAutomation - Boolean
var isAutomation = true;
console.log("isAutomation : " + isAutomation + " :: typeof :: " + typeof(isAutomation));

// e) hasPlaywright - Declared but not assigned (undefined)
var hasPlaywright;
console.log("hasPlaywright : " + hasPlaywright + " :: typeof :: " + typeof(hasPlaywright));
